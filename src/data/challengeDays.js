// Build category color map from phases (for DayView badge coloring)
export function getCategoryColors(phases) {
  const colors = {};
  for (const phase of phases) {
    for (const d of phase.days) {
      colors[d] = { accent: phase.color, label: phase.label };
    }
  }
  return colors;
}

